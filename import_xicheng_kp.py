def import_tree():
    with app.app_context():
        db = get_db()
        total_nodes = 0
        new_nodes = 0

        for subject, chapters in KNOWLEDGE_TREE.items():
            sid = ensure_subject(subject, IMPORT_UUID, claim=True)
            if sid:
                total_nodes += 1

            for chapter_name, points in chapters:
                cid = ensure_node(chapter_name, 2, subject, IMPORT_UUID, sid, claim=True)
                if cid:
                    total_nodes += 1

                for point_name in points:
                    nid = ensure_node(point_name, 3, subject, IMPORT_UUID, cid, claim=True)
                    total_nodes += 1
                    if nid:
                        # 检查是否为新创建（通过检查 created_at）
                        cur = db.execute(
                            "SELECT id FROM knowledge_points WHERE level=3 AND name=? AND parent_id=?",
                            (point_name, cid)
                        )
                        existing = cur.fetchone()
                        # ensure_node 已处理幂等，这里只统计
                        pass

        print(f"✅ 导入完成：共 {len(KNOWLEDGE_TREE)} 个学科，{total_nodes} 个节点")
        print(f"   (幂等设计，重复运行不会产生重复节点)")

        # 输出各学科节点统计
        for subject, chapters in KNOWLEDGE_TREE.items():
            chap_count = len(chapters)
            point_count = sum(len(p) for _, p in chapters)
            print(f"   {subject}: {chap_count} 章, {point_count} 个知识点")


if __name__ == '__main__':
    import_tree()
